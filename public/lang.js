var currentLang = sessionStorage.getItem('pos_lang') || 'th';

function changeLanguage(lang) {
  currentLang = lang;
  sessionStorage.setItem('pos_lang', lang);
  
  const langSelector = document.getElementById('lang-selector');
  if (langSelector) langSelector.value = lang;
  

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = i18n[lang][key];
      } else {
        const icon = el.querySelector('i');
        if (icon) {
          el.innerHTML = icon.outerHTML + " " + i18n[lang][key];
        } else {
          el.innerHTML = i18n[lang][key];
        }
      }
    }
  });

  // 🌟 [เพิ่มตรงนี้] ยิงคำสั่งบอกจอลูกค้าให้เปลี่ยนภาษาตาม
  if (typeof syncLanguageToCFD === 'function') {
    syncLanguageToCFD(lang);
  }
}

function toggleLanguage() {
  const newLang = currentLang === 'th' ? 'en' : 'th';
  changeLanguage(newLang);
}
